#!/usr/bin/env bash
# Writes infra/kong/kong.dev.yml: kong.yml with every upstream on the host
# (http://auth-service:3001 → http://host.docker.internal:3001), plus the development sign-in
# routes (/api/dev), which the real config never exposes. auth-service refuses /api/dev itself
# unless DEV_LOGIN=on outside production.
set -euo pipefail
cd "$(dirname "$0")/.."
src=infra/kong/kong.yml
out=infra/kong/kong.dev.yml
{
  echo "# GENERATED by scripts/kong-dev-config.sh from kong.yml for local development. Don't edit."
  sed -E 's#http://[a-z-]+:([0-9]+)#http://host.docker.internal:\1#' "$src"
  cat <<'YAML'

  # development only: one-click sign-in for the web and phone apps (DEV_LOGIN=on)
  - name: auth-dev
    url: http://host.docker.internal:3001
    routes:
      - name: dev-sign-in-routes
        paths: ["/api/dev"]
        strip_path: false
YAML
} > "$out"
echo "wrote $out"
